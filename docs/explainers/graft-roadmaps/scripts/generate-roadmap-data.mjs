import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(scriptDir, "..");
const roadmapPath = resolve(siteRoot, "../../design/SURFACE_graft-managed-workspace-store-roadmap.md");
const snapshotPath = resolve(siteRoot, "data/live-snapshot.json");
const outputPath = resolve(siteRoot, "src/generated-roadmap-data.js");

const [roadmapSource, snapshotSource] = await Promise.all([
  readFile(roadmapPath, "utf8"),
  readFile(snapshotPath, "utf8"),
]);
const snapshot = JSON.parse(snapshotSource);

const sectionMatches = [...roadmapSource.matchAll(/^## (G\d+) - ([^\n]+)$/gm)];
const goalposts = [];
const tasks = [];
let issueNumber = snapshot.managed.issueStart;

for (const [index, match] of sectionMatches.entries()) {
  const id = match[1];
  const title = match[2].trim();
  const start = match.index;
  const end = sectionMatches[index + 1]?.index ?? roadmapSource.length;
  const section = roadmapSource.slice(start, end);
  const goal = section.match(/### Goalpost\n\n([\s\S]*?)(?=\n\n(?:All durable|git-warp|\| Slice|###))/)?.[1]
    ?.replace(/\n/g, " ")
    .replace(/\s+/g, " ")
    .trim() ?? "";
  const release = section.match(/### Release Checkpoint\n\n([^\n]+)/)?.[1]?.trim() ?? null;
  const statusMatch = roadmapSource.match(new RegExp(`^\\| ${id}[^|]*\\| ([^|]+) \\| ([^|]+) \\|$`, "m"));
  const statusLabel = statusMatch?.[1]?.trim() ?? "Not started";
  const statusNote = statusMatch?.[2]?.trim() ?? "";
  const milestone = snapshot.managed.milestones[id];
  const goalpost = {
    id,
    short: id,
    title,
    goal,
    release,
    status: id === "G0" ? "complete" : id === "G1" ? "active" : "planned",
    trackerStatus: statusLabel,
    statusNote,
    kind: "goalpost",
    milestone,
    url: `https://github.com/${snapshot.repository}/milestone/${milestone.number}`,
    tasks: [],
  };

  for (const row of section.matchAll(/^\| (G\d+\.\d+) - ([^|]+) \| ([^|]+) \|$/gm)) {
    const task = {
      id: row[1].trim(),
      short: row[1].trim(),
      title: row[2].trim().replaceAll("`", ""),
      summary: row[3].trim().replaceAll("`", ""),
      issueNumber,
      status: snapshot.managed.closedIssues.includes(issueNumber) ? "complete" : "planned",
      kind: "task",
      milestone: id,
      url: `https://github.com/${snapshot.repository}/issues/${issueNumber}`,
    };
    issueNumber += 1;
    goalpost.tasks.push(task.id);
    tasks.push(task);
  }

  goalposts.push(goalpost);
}

const expectedIssueAfterLast = snapshot.managed.issueEnd + 1;
if (issueNumber !== expectedIssueAfterLast) {
  throw new Error(`managed issue mapping ended at ${issueNumber - 1}, expected ${snapshot.managed.issueEnd}`);
}

const managedEdges = [
  ["G0", "G1"],
  ["G1", "G2"],
  ["G2", "G3"],
  ["G3", "G4"],
  ["G4", "G5"],
  ["G5", "G6"],
  ["G6", "G7"],
  ["G7", "G8"],
  ["G8", "G12"],
  ["G3", "G10"],
  ["G4", "G11"],
  ["G5", "G9"],
  ["G6", "G9"],
].map(([source, target]) => ({ source, target, kind: "roadmap", label: "roadmap sequence" }));

const taskNodes = [];
const taskEdges = [];
for (const goalpost of goalposts) {
  const entryId = `${goalpost.id}-entry`;
  const exitId = `${goalpost.id}-exit`;
  taskNodes.push(
    {
      ...goalpost,
      id: entryId,
      short: `${goalpost.id} · ENTER`,
      title: goalpost.title,
      kind: "gate",
      summary: goalpost.goal,
    },
    {
      ...goalpost,
      id: exitId,
      short: `${goalpost.id} · GATE`,
      title: goalpost.release ?? `${goalpost.id} exit gate`,
      kind: "gate",
      summary: `${goalpost.tasks.length} PR-sized task issues make up this goalpost.`,
    },
  );
  const memberTasks = tasks.filter((task) => task.milestone === goalpost.id);
  taskNodes.push(...memberTasks);
  for (const task of memberTasks) {
    taskEdges.push(
      { source: entryId, target: task.id, kind: "membership", label: "goalpost member" },
      { source: task.id, target: exitId, kind: "membership", label: "contributes to gate" },
    );
  }
}

for (const edge of managedEdges) {
  taskEdges.push({
    source: `${edge.source}-exit`,
    target: `${edge.target}-entry`,
    kind: edge.kind,
    label: edge.label,
  });
}

const generated = {
  snapshotAt: snapshot.snapshotAt,
  repository: snapshot.repository,
  mainSha: snapshot.mainSha,
  echoDesignSha: snapshot.echoDesignSha,
  managed: {
    goalposts,
    tasks,
    edges: managedEdges,
    taskNodes,
    taskEdges,
  },
  echo: snapshot.echo,
};

const banner = "// Generated by scripts/generate-roadmap-data.mjs. Do not edit by hand.\n";
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${banner}export const roadmapData = ${JSON.stringify(generated, null, 2)};\n`, "utf8");

console.log(`Generated ${goalposts.length} goalposts and ${tasks.length} managed task issues.`);
